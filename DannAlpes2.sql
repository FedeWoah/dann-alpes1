SELECT c.NOMBRE AS CIUDAD,
       h.NOMBRE AS HOTEL,
       SUM(r.PRECIO_TOTAL) AS INGRESO_TOTAL
FROM RESERVA r
JOIN HOTEL h
  ON r.ID_HOTEL = h.ID_HOTEL
JOIN CIUDAD c
  ON h.ID_CIUDAD = c.ID_CIUDAD
WHERE r.FECHA_RESERVA BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
  AND r.ESTADO = 'ACTIVA'
GROUP BY c.NOMBRE, h.NOMBRE
ORDER BY c.NOMBRE, h.NOMBRE;

