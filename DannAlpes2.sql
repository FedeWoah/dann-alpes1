       h.NOMBRE AS HOTEL,
       s.NOMBRE AS SERVICIO,
       COUNT(*) AS TOTAL_USOS
FROM RESERVA_SERVICIO rs
JOIN RESERVA r
  ON rs.ID_RESERVA = r.ID_RESERVA
JOIN HOTEL h
  ON r.ID_HOTEL = h.ID_HOTEL
JOIN CIUDAD c
  ON h.ID_CIUDAD = c.ID_CIUDAD
JOIN SERVICIO s
  ON rs.ID_SERVICIO = s.ID_SERVICIO
WHERE r.FECHA_RESERVA BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
  AND r.ESTADO = 'ACTIVA'
GROUP BY c.NOMBRE, h.NOMBRE, s.NOMBRE
ORDER BY TOTAL_USOS DESC;