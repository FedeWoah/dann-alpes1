SELECT c.NOMBRE AS CIUDAD,
       h.NOMBRE AS HOTEL,
       th.NOMBRE AS TIPO_HABITACION,
       COUNT(*) AS TOTAL_RESERVAS
FROM RESERVA r
JOIN HOTEL h
  ON r.ID_HOTEL = h.ID_HOTEL
JOIN CIUDAD c
  ON h.ID_CIUDAD = c.ID_CIUDAD
JOIN TIPO_HABITACION th
  ON r.ID_TIPO = th.ID_TIPO
WHERE r.FECHA_RESERVA BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
  AND r.ESTADO = 'ACTIVA'
GROUP BY c.NOMBRE, h.NOMBRE, th.NOMBRE
ORDER BY TOTAL_RESERVAS DESC;

