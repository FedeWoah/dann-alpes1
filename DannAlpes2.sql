SELECT r.FECHA_RESERVA,
       c.NOMBRE AS NOMBRE_CIUDAD,
       h.NOMBRE AS NOMBRE_HOTEL, 
       COUNT(*) AS TOTAL_RESERVAS
FROM RESERVA r
JOIN HOTEL h ON r.ID_HOTEL = h.ID_HOTEL
JOIN CIUDAD c ON h.ID_CIUDAD = c.ID_CIUDAD
WHERE r.FECHA_RESERVA BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
GROUP BY r.FECHA_RESERVA, c.NOMBRE, h.NOMBRE
ORDER BY r.FECHA_RESERVA, c.NOMBRE, h.NOMBRE;

