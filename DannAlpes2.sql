SELECT r.FECHA_ENTRADA,
       c.NOMBRE AS CIUDAD,
       h.NOMBRE AS HOTEL,
       SUM(r.NUM_ADULTOS + r.NUM_MENORES) AS TOTAL_HUESPEDES
FROM RESERVA r
JOIN HOTEL h
  ON r.ID_HOTEL = h.ID_HOTEL
JOIN CIUDAD c
  ON h.ID_CIUDAD = c.ID_CIUDAD
WHERE r.FECHA_ENTRADA BETWEEN DATE '2026-01-01' AND DATE '2026-12-31'
GROUP BY r.FECHA_ENTRADA, c.NOMBRE, h.NOMBRE
ORDER BY r.FECHA_ENTRADA, c.NOMBRE, h.NOMBRE;

