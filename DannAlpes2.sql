SELECT h.ID_HABITACION,
       h.NUMERO,
       th.NOMBRE AS TIPO_HABITACION,
       th.CAPACIDAD,
       th.VISTA,
       th.COSTO_ALTA AS PRECIO_NOCHE
FROM HABITACION h
JOIN TIPO_HABITACION th
  ON h.ID_TIPO = th.ID_TIPO
 AND h.ID_HOTEL = th.ID_HOTEL
LEFT JOIN RESERVA r
  ON r.ID_HOTEL = h.ID_HOTEL
 AND r.ID_TIPO = h.ID_TIPO
 AND r.ESTADO = 'ACTIVA'
 AND r.FECHA_ENTRADA < DATE '2026-05-13'
 AND r.FECHA_SALIDA > DATE '2026-05-10'
WHERE h.ID_HOTEL = 1
  AND h.DISPONIBLE = 'SI'
  AND r.ID_RESERVA IS NULL
ORDER BY h.NUMERO;

