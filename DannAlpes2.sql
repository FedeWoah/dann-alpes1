CREATE TABLE CIUDAD (
  ID_CIUDAD NUMBER(10) NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  PAIS VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_CIUDAD PRIMARY KEY (ID_CIUDAD)
);

CREATE TABLE CLIENTE (
  ID_CLIENTE NUMBER(10) NOT NULL,
  IDENTIFICACION VARCHAR2(20) NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  APELLIDOS VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(200) NOT NULL,
  TELEFONO VARCHAR2(20),
  CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT UQ_CLIE_IDEN UNIQUE (IDENTIFICACION),
  CONSTRAINT UQ_CLIE_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE HOTEL (
  ID_HOTEL NUMBER(10) NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  DIRECCION VARCHAR2(100),
  TELEFONO VARCHAR2(50),
  DESCRIPCION VARCHAR2(500),
  ID_CIUDAD NUMBER(10) NOT NULL,
  CONSTRAINT PK_HOTEL PRIMARY KEY (ID_HOTEL),
  CONSTRAINT FK_HOTEL_CIUDAD FOREIGN KEY (ID_CIUDAD)
    REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE TIPO_HABITACION (
  ID_TIPO NUMBER(10) NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  COSTO_BAJA NUMBER(10,2) NOT NULL,
  COSTO_ALTA NUMBER(10,2) NOT NULL,
  DIMENSIONES NUMBER(5,2),
  VISTA VARCHAR2(100),
  CAPACIDAD NUMBER(3) NOT NULL,
  ID_HOTEL NUMBER(10) NOT NULL,
  CONSTRAINT PK_TIPO_HAB PRIMARY KEY (ID_TIPO),
  CONSTRAINT FK_TIPO_HOTEL FOREIGN KEY (ID_HOTEL)
    REFERENCES HOTEL(ID_HOTEL),
  CONSTRAINT CK_TH_COSTO1 CHECK (COSTO_BAJA >= 0),
  CONSTRAINT CK_TH_COSTO2 CHECK (COSTO_ALTA >= 0),
  CONSTRAINT CK_TH_CAP CHECK (CAPACIDAD > 0),
  CONSTRAINT UQ_TH_HOTEL_NOM UNIQUE (ID_HOTEL, NOMBRE)
);

CREATE TABLE HABITACION (
  ID_HABITACION NUMBER(10) NOT NULL,
  NUMERO VARCHAR2(10) NOT NULL,
  PISO NUMBER(3),
  DISPONIBLE VARCHAR2(2) DEFAULT 'SI' NOT NULL,
  ID_HOTEL NUMBER(10) NOT NULL,
  ID_TIPO NUMBER(10) NOT NULL,
  CONSTRAINT PK_HAB PRIMARY KEY (ID_HABITACION),
  CONSTRAINT FK_HAB_HOTEL FOREIGN KEY (ID_HOTEL)
    REFERENCES HOTEL(ID_HOTEL),
  CONSTRAINT FK_HAB_TIPO FOREIGN KEY (ID_TIPO)
    REFERENCES TIPO_HABITACION(ID_TIPO),
  CONSTRAINT CK_HAB_DISP CHECK (DISPONIBLE IN ('SI','NO')),
  CONSTRAINT UQ_HAB_HOTEL_NUM UNIQUE (ID_HOTEL, NUMERO)
);

CREATE TABLE SERVICIO (
  ID_SERVICIO NUMBER(10) NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  DESCRIPCION VARCHAR2(500),
  TIPO_COSTO VARCHAR2(20) NOT NULL,
  PRECIO NUMBER(10,2) NOT NULL,
  APLICA VARCHAR2(20) NOT NULL,
  CONSTRAINT PK_SERV PRIMARY KEY (ID_SERVICIO),
  CONSTRAINT UQ_SERV_NOM UNIQUE (NOMBRE),
  CONSTRAINT CK_SERV_TIPO CHECK (TIPO_COSTO IN ('FIJO','CONSUMO')),
  CONSTRAINT CK_SERV_APL CHECK (APLICA IN ('RESERVA','NOCHE','PERSONA')),
  CONSTRAINT CK_SERV_PRECIO CHECK (PRECIO >= 0)
);

CREATE TABLE TIPO_SERVICIO (
  ID_TIPO NUMBER(10) NOT NULL,
  ID_SERVICIO NUMBER(10) NOT NULL,
  PRECIO_ESPECIAL NUMBER(10,2) NOT NULL,
  CONSTRAINT PK_TS PRIMARY KEY (ID_TIPO, ID_SERVICIO),
  CONSTRAINT FK_TS_TIPO FOREIGN KEY (ID_TIPO)
    REFERENCES TIPO_HABITACION(ID_TIPO),
  CONSTRAINT FK_TS_SERV FOREIGN KEY (ID_SERVICIO)
    REFERENCES SERVICIO(ID_SERVICIO),
  CONSTRAINT CK_TS_PRECIO CHECK (PRECIO_ESPECIAL >= 0)
);

CREATE TABLE RESERVA (
  ID_RESERVA NUMBER(10) NOT NULL,
  FECHA_ENTRADA DATE NOT NULL,
  FECHA_SALIDA DATE NOT NULL,
  FECHA_RESERVA DATE NOT NULL,
  NUM_ADULTOS NUMBER(3) NOT NULL,
  NUM_MENORES NUMBER(3) NOT NULL,
  PRECIO_TOTAL NUMBER(10,2) NOT NULL,
  ESTADO VARCHAR2(20) NOT NULL,
  ID_CLIENTE NUMBER(10) NOT NULL,
  ID_TIPO NUMBER(10) NOT NULL,
  ID_HOTEL NUMBER(10) NOT NULL,
  CONSTRAINT PK_RES PRIMARY KEY (ID_RESERVA),
  CONSTRAINT FK_RES_CLI FOREIGN KEY (ID_CLIENTE)
    REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT FK_RES_TIPO FOREIGN KEY (ID_TIPO)
    REFERENCES TIPO_HABITACION(ID_TIPO),
  CONSTRAINT FK_RES_HOT FOREIGN KEY (ID_HOTEL)
    REFERENCES HOTEL(ID_HOTEL),
  CONSTRAINT CK_RES_FECHAS CHECK (FECHA_SALIDA > FECHA_ENTRADA),
  CONSTRAINT CK_RES_ADULTOS CHECK (NUM_ADULTOS >= 1),
  CONSTRAINT CK_RES_MENORES CHECK (NUM_MENORES >= 0),
  CONSTRAINT CK_RES_PRECIO CHECK (PRECIO_TOTAL >= 0),
  CONSTRAINT CK_RES_ESTADO CHECK (ESTADO IN ('ACTIVA','CANCELADA','FINALIZADA'))
);

CREATE TABLE RESERVA_SERVICIO (
  ID_RESERVA_SERVICIO NUMBER(10) NOT NULL,
  ID_RESERVA NUMBER(10) NOT NULL,
  ID_SERVICIO NUMBER(10) NOT NULL,
  CANTIDAD NUMBER(3),
  PRECIO_APLICADO NUMBER(10,2) NOT NULL,
  CONSTRAINT PK_RS PRIMARY KEY (ID_RESERVA_SERVICIO),
  CONSTRAINT FK_RS_RES FOREIGN KEY (ID_RESERVA)
    REFERENCES RESERVA(ID_RESERVA),
  CONSTRAINT FK_RS_SERV FOREIGN KEY (ID_SERVICIO)
    REFERENCES SERVICIO(ID_SERVICIO),
  CONSTRAINT CK_RS_CANT CHECK (CANTIDAD IS NULL OR CANTIDAD > 0),
  CONSTRAINT CK_RS_PRECIO CHECK (PRECIO_APLICADO >= 0)
);



